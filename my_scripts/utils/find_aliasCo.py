## ==== NORMALIZATION & DENORMALIZATION =========

REGEX_SPACE,REGEX_CAMEL = (
    re.compile(r'\s+'), # whitespace normalization
    re.compile(r'(?<=[a-z])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])') # split camel-case
)
def normalize_entity(ent:str) -> str :
    """
    Normalize a company/entity name into a canonical form suitable for
    alias comparison.

    Workflow
    --------
        1. Split CamelCase words (e.g. 'JPMorgan' -> 'JP Morgan').
        2. Convert to lowercase and remove punctuation using `rapidfuzz.utils.default_process(...)`.
        3. Collapse consecutive whitespaces into a single space.

    The resulting string preserves word boundaries so that `denormalize_entity(...)` can later reconstruct a flexible regex.

    Examples
    --------
    >>> normalize_entity("J.P. Morgan Chase")
    'j p morgan chase'

    >>> normalize_entity("JPMorgan Chase")
    'jp morgan chase'

    >>> normalize_entity("Cash-App")
    'cash app'

    >>> normalize_entity("Capital   One, Financial")
    'capital one financial'

    """
    # recover CamelCase before lower-casing ----
    ent = REGEX_CAMEL.sub(' ', ent)
    # ----
    # lowercase + remove punctuation ----
    ent = default_process(ent)
    # ----
    # collapse repeated spaces ----
    ent = REGEX_SPACE.sub(' ',ent)
    # ----
    return ent.strip()


REGEX_ALNUM,SEP_PATTERN = (
    re.compile(r'[A-Za-z0-9]+'), # identify consecutive alphanumeric chars
    r'[\s.,-]*' # common word-separators
)
def denormalize_entity(ent:str) ->str :
    """
    Convert a normalized entity into a regex pattern capable of matching
    common surface variations in free text.

    Matching rules
    --------------
        * The first word is always required.
        * The second word (if present) is also required.
        * Remaining words become optional suffixes.
        * Word separators (' ', '.', ',', '-') are treated as equivalent.
        * Zero separators are allowed, so concatenated words also match (e.g. 'CashApp', 'JPMorgan').

    Examples
    --------
    >>> denormalize_entity("equifax")
    '\\bequifax\\b'

    >>> denormalize_entity("american express")
    '\\bamerican[\\s.,-]*express\\b'

    >>> denormalize_entity("jp morgan chase")
    '\\bjp[\\s.,-]*morgan(?:[\\s.,-]*chase)?\\b'

    """
    words = REGEX_ALNUM.findall(ent)
    # base ----
    pattern = re.escape(words[0])
    if len(words) == 1 : # handle sinle word cases
        return r'\b' + pattern + r'\b'
    n_required = 2 if min(len(words[0]),len(words[1]))>2 else 3
    for word in words[1:n_required] : 
        pattern += (SEP_PATTERN + re.escape(word))
    # If either of the first two words is very short (≤2 characters),
    # require the first three words before making the remaining suffix optional.
    # This reduces false positives caused by fuzzy matching.
    # ----
    # optional ----
    for word in words[n_required:] :
        pattern += f"(?:{SEP_PATTERN}{re.escape(word)})?"
    # ----
    return r'\b' + pattern + r'\b'

