## ==== COUNTER =========

def _is_alias(s1:str,s2:str,*,score_cutoff:float=0.96) -> bool :
    """ `rapidfuzz.distance.Levenshtein.normalized_similarity(...)` wrapper """
    # regex matching uses 'Levenshtein Distance'
    return bool(
        Levenshtein.normalized_similarity(
            s1,s2,
            score_cutoff=score_cutoff
        )
    )
    
def merged_counter(list_of_list:list[list],n:int|None=10,*,fuzzy:bool=True,score_cutoff:float=0.96) -> list[tuple] :
    """
    Flatten a nested list of strings and return the most frequent elements via `collections.Counter(...).most_common(n)`.

    When `fuzzy=True`, similar strings are greedily consolidated before computing the final frequencies 
    using `rapidfuzz.distance.Levenshtein.normalized_similarity(...)`.

    """
    merged = itertools.chain.from_iterable(list_of_list)
    counted = Counter(merged)
    if not fuzzy : return counted.most_common(n)
    # even though we have counted all unique strings, we can consolidate further by fuzzy-match
    k = 1
    sorted_desc = counted.most_common(k+1)
    while len(sorted_desc)>k :
        unique = sorted_desc[:k]
        current_entity,count = sorted_desc[k]
        alias = None
        for visited_entity,_ in unique :
            if _is_alias(current_entity,visited_entity,score_cutoff=score_cutoff) :
                alias = True
                # merge the current count with existing alias count
                counted[visited_entity] += count
                del counted[current_entity]
                break
        if alias is None : k += 1
        # always reorder the elements before moving to next iteration
        # this is a greedy algorithm, 
        #   that finds the largest existing group with similar name of the current entity to merge
        #   if no existing match found, current entity remains its own group
        # Example 
        #   original : counted={str1:10, str2:5, str3:2}
        #   step-1 : _is_alias(str1,str2)=True, {str1:(10+5), str3:2}-->counted
        #   step-2 : _is_alias(str1,str3)=False, {str1:15, str3:2}-->counted ; _is_alias(str2,str3) is not considered any more
        sorted_desc = counted.most_common(k+1)
    # when len(most_common(k+1))>k fails, it implies no more elements to explore
    return sorted_desc[:n]

