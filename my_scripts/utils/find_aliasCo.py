"""
    It helps us finding small variation in company names, such as -
        ('citi','citi bank')
        ('jpmorgan','jp morgan')
    etc.

"""
import re
from rapidfuzz.distance import Levenshtein
from rapidfuzz.utils import default_process
from collections import Counter
import itertools


## ==== SEARCH =========

def search_pattern(alias:str) -> str :
    """
    Construct a fuzzy regex pattern for a normalized company alias.

    The pattern generated by `denormalize_entity(...)` is wrapped with fuzzy matching constraints supported by the `regex` module.
    Maximum total edit distance increases with alias length, but is capped at 2.
    """
    n = min(2,len(alias)//6)
    pat = denormalize_entity(alias)
    return f"(?:{pat}){{i<=2,s<=1,d<=1,e<={n}}}"

